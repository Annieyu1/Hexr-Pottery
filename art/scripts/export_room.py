"""Export the study room from Blender to Unity (FBX).

Run inside Blender with art/blender/HexR_StudyRoom.blend open:
    exec(open("<repo>/art/scripts/export_room.py").read())

Destructive on the open session (flattens imports, applies bevels, resets origins) and does NOT save
the .blend. Reload the file afterwards (File > Revert) to get the editable source back.

Output: <repo>/Assets/Art/Environment/HexR_StudyRoom.fbx   (1 unit = 1 m, Y up after import)
        <repo>/art/textures/Palette_Base.png + palette_map.json (generated by palette.py: one atlas for all flat colours)

Open the .blend and run this in separate calls: File > Revert, then exec (join() needs a fresh context).
"""
import bpy, os
from mathutils import Vector, Matrix

REPO = os.path.dirname(os.path.dirname(os.path.dirname(bpy.data.filepath)))
OUT = os.path.join(REPO, "Assets", "Art", "Environment", "HexR_StudyRoom.fbx")

# stale stage-A boxes that were replaced by Sketchfab models: keep them out of the export
for n in ("Bookshelf", "Lamp", "Plant", "Painting_A"):
    o = bpy.data.objects.get(n)
    if o and o.type == 'MESH' and o.hide_render:
        o.name = "GB_old_" + n

def descendants(o):
    out = [o]
    for c in o.children:
        out += descendants(c)
    return out

def flatten(root_name, new_name):
    """Bake the import hierarchy into one mesh object at identity transform."""
    root = bpy.data.objects[root_name]
    meshes = [o for o in descendants(root) if o.type == 'MESH']
    mws = {o: o.matrix_world.copy() for o in meshes}
    for o in meshes:
        o.data = o.data.copy()
        o.data.transform(mws[o])
        o.parent = None
        o.matrix_world = Matrix.Identity(4)
    for e in [o for o in descendants(root) if o.type != 'MESH']:
        bpy.data.objects.remove(e, do_unlink=True)
    bpy.ops.object.select_all(action='DESELECT')
    for o in meshes:
        o.select_set(True)
    bpy.context.view_layer.objects.active = meshes[0]
    if len(meshes) > 1:
        bpy.ops.object.join()
    o = bpy.context.active_object
    o.name = new_name; o.data.name = new_name
    bpy.ops.object.select_all(action='DESELECT')
    return o

for src, dst in {"SF_Bookshelf": "Bookshelf", "SF_Lamp": "Lamp", "SF_Plant": "Plant", "SF_WallArt": "WallArt"}.items():
    flatten(src, dst)

EXPORT = ["Room_Shell", "Floor_Planks", "Rug", "Desk", "Lamp", "PenHolder", "Book_Stack", "Mug",
          "SoftBall_L", "SoftBall_R", "Pedestal_L", "Pedestal_R", "AnswerPad",
          "Bookshelf", "Plant", "WallArt", "Wall_Shelf", "Picture_Frame",
          "SideTable", "Records", "Turntable", "FloorLamp",
          "Window_Frame", "Window_Blinds", "Window_Mullions", "Sky_Backdrop"]

# bake modifiers (bevel) into the mesh
dg = bpy.context.evaluated_depsgraph_get()
for n in EXPORT:
    o = bpy.data.objects[n]
    if o.modifiers:
        me = bpy.data.meshes.new_from_object(o.evaluated_get(dg))
        old = o.data
        o.modifiers.clear()
        o.data = me
        me.name = n
        if old.users == 0:
            bpy.data.meshes.remove(old)

# many flat-colour materials -> one palette atlas + UV0 (see palette.py)
exec(open(os.path.join(REPO, "art", "scripts", "palette.py")).read())
apply_palette(EXPORT, os.path.join(REPO, "art", "textures"))

# identity rotation/scale; origin at bottom-centre (balls keep their centre as pivot)
for n in EXPORT:
    o = bpy.data.objects[n]
    if o.data.users > 1:
        continue
    o.data.transform(o.matrix_world)
    o.matrix_world = Matrix.Identity(4)
    if n in ("Room_Shell",):
        continue
    pts = [Vector(v.co) for v in o.data.vertices]
    mn = Vector((min(p.x for p in pts), min(p.y for p in pts), min(p.z for p in pts)))
    mx = Vector((max(p.x for p in pts), max(p.y for p in pts), max(p.z for p in pts)))
    off = Vector(((mn.x+mx.x)/2, (mn.y+mx.y)/2, mn.z))
    o.data.transform(Matrix.Translation(-off))
    o.location = off

bpy.context.view_layer.update()
tris = 0; mats = set()
for n in EXPORT:
    o = bpy.data.objects[n]
    o.data.calc_loop_triangles(); tris += len(o.data.loop_triangles)
    mats |= {m.name for m in o.data.materials if m}
print("objects", len(EXPORT), "tris", tris, "materials", len(mats))

bpy.ops.object.select_all(action='DESELECT')
for n in EXPORT + ["Player_Eye_Ref"]:
    o = bpy.data.objects[n]
    o.hide_set(False); o.hide_viewport = False
    o.select_set(True)
os.makedirs(os.path.dirname(OUT), exist_ok=True)
bpy.ops.export_scene.fbx(
    filepath=OUT, use_selection=True, object_types={'MESH', 'EMPTY'},
    apply_unit_scale=True, apply_scale_options='FBX_SCALE_ALL', global_scale=1.0,
    axis_forward='-Z', axis_up='Y', bake_space_transform=True,
    mesh_smooth_type='FACE', use_mesh_modifiers=True, add_leaf_bones=False,
    path_mode='COPY', embed_textures=True)
print("exported", OUT, os.path.getsize(OUT)//1024, "KB")
